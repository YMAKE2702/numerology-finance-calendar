"""Расчёт «чисел силы» по дате рождения.

ВАЖНО: число силы — это НЕ число жизненного пути.
- Число жизненного пути — ОДНА цифра (1–9, 11, 22, 33). Считается в `life_path.py`.
- Числа силы — НАБОР цифр, которые для конкретного человека считаются благоприятными.
  По системе, использованной в каноне проекта, в числа силы входят:

1. День рождения (например, 27).
2. Число жизненного пути (например, 11 — мастер-число).
3. Составляющие числа дня рождения (для 27 это 2 и 7).
4. Сумма цифр месяца рождения с редукцией (для 02 → 2, для 11 → 2, для 12 → 3).
5. Составляющие числа жизненного пути, если оно не мастер-число
   (для числа 11 не сводится — оставляем 11).
6. Дополнительные числа, заданные пользователем вручную.

Отличие от классического алгоритма для числа жизненного пути:
- День рождения сохраняем как набор цифр (2 и 7 — разные «коды»).
- Месяц рождения редуцируем до одного числа (по классике).
"""

from datetime import date


def sum_digits_reduced(n: int) -> int:
    """Сумма цифр числа с редукцией до 1–9."""
    total = sum(int(d) for d in str(abs(n)))
    while total > 9:
        total = sum(int(d) for d in str(total))
    return total


def birthday_components(birth_date: date) -> set[int]:
    """Цифры дня рождения (например, для 27 → {2, 7}).

    Для дня рождения сохраняем набор цифр, а не сумму:
    27 — это отдельный «код» из 2 и 7, каждая цифра значима.
    """
    return {int(d) for d in str(birth_date.day)}


def month_component(birth_date: date) -> int:
    """Сумма цифр месяца рождения с редукцией до 1–9.

    Например:
        02 → 0+2 = 2
        11 → 1+1 = 2
        12 → 1+2 = 3
    """
    return sum_digits_reduced(birth_date.month)


def power_numbers(birth_date: date, life_path: int, extra: list[int] | None = None) -> list[int]:
    """Возвращает отсортированный список чисел силы.

    Args:
        birth_date: дата рождения.
        life_path: число жизненного пути (ОДНА цифра 1–9, 11, 22, 33).
        extra: дополнительные числа, заданные пользователем вручную.

    Returns:
        Список уникальных чисел, отсортированных по возрастанию.
    """
    result: set[int] = set()

    # День рождения
    result.add(birth_date.day)

    # Число жизненного пути (мастер-числа сохраняются)
    result.add(life_path)

    # Составляющие дня рождения (для 27 → 2 и 7)
    result.update(birthday_components(birth_date))

    # Сумма цифр месяца рождения (для 02 → 2)
    result.add(month_component(birth_date))

    # Составляющие числа жизненного пути, только если оно НЕ мастер-число
    # (мастер-числа 11, 22, 33 не сводим — это их суть)
    if life_path not in {11, 22, 33}:
        for d in str(life_path):
            result.add(int(d))

    # Дополнительные числа
    if extra:
        result.update(extra)

    return sorted(result)
